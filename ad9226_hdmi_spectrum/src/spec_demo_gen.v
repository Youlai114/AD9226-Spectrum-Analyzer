// ============================================================================
// spec_demo_gen.v  --  内部测试数据源 (两个可选的频谱数据发生器)
//
//   1) spec_tone_gen : 单音正弦测试数据 (默认使用)
//        从 tone_rom 读出"200kHz 正弦经 2048 点 FFT 后的幅度谱", 每帧突发写入
//        1024 个频点, 并叠加少量随机噪声, 让噪声底像真实 ADC 一样抖动。
//        tone_rom 的内容由 tools/gen_tone_rom.py 用真实 FFT 算出并写回本文件,
//        换频率/采样率只改那个脚本:
//            python tools/gen_tone_rom.py --f0 200e3 --fs 2e6 --nfft 2048
//
//   2) spec_demo_gen : 多峰扫频演示 (想要明显的动态效果时用)
//        噪声底 + 5 个窄带峰, 其中两个峰按三角波来回漂移。
//
//   两者输出协议完全相同, 在 video_top.v 里换实例即可。
//   协议见 spec_data_if.v 文件头。
// ============================================================================
module spec_tone_gen (
    input             I_clk        ,
    input             I_rst_n      ,
    input      [1:0]  I_span       ,   // 显示跨度选择 (选 tone_rom 的层)
    input             I_frame_tick ,   // 每帧一个脉冲 (与 I_clk 同步)
    output reg        O_frame_start,
    output reg        O_wr_en      ,
    output reg [9:0]  O_wr_addr    ,
    output reg [15:0] O_wr_mag
);

    reg [10:0] cnt;        // 0..1025
    reg        busy;
    reg [15:0] lfsr;
    reg [9:0]  addr_d1;    // 与 rom_q 对齐的地址

    //------------------------------------------------------------------
    // 幅度谱 ROM (同步读, 综合成 BSRAM)
    //------------------------------------------------------------------
    wire [15:0] rom_q;

    tone_rom u_tone_rom (
        .I_clk  (I_clk             ),
        .I_addr ({I_span, cnt[9:0]}),   // {量程, 频点}
        .O_mag  (rom_q             )
    );

    //------------------------------------------------------------------
    // 叠加噪声: ±8 个码 (对 0dBFS 峰值无影响, 对噪声底是 ±3dB 的抖动)
    //------------------------------------------------------------------
    wire [16:0] nz_a = {1'b0, rom_q} + {1'b0, {12'd0, lfsr[7:4]}};
    wire [16:0] nz_b = (nz_a >= 17'd7) ? (nz_a - 17'd7) : 17'd0;
    wire [15:0] mag_c = (nz_b > 17'd65535) ? 16'd65535 : nz_b[15:0];

    //------------------------------------------------------------------
    // 帧突发
    //   ROM 有 1 拍读延迟, 所以地址也要延 1 拍, 保证 addr/mag 对齐
    //------------------------------------------------------------------
    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            cnt           <= 11'd0;
            busy          <= 1'b0;
            lfsr          <= 16'h1ACE;
            addr_d1       <= 10'd0;
            O_frame_start <= 1'b0;
            O_wr_en       <= 1'b0;
            O_wr_addr     <= 10'd0;
            O_wr_mag      <= 16'd0;
        end else begin
            O_frame_start <= 1'b0;
            addr_d1       <= cnt[9:0];

            if (busy)
                lfsr <= {lfsr[14:0], lfsr[15] ^ lfsr[13] ^ lfsr[12] ^ lfsr[10]};

            if (!busy) begin
                O_wr_en <= 1'b0;
                if (I_frame_tick) begin
                    busy          <= 1'b1;
                    cnt           <= 11'd0;
                    O_frame_start <= 1'b1;
                end
            end else begin
                cnt <= cnt + 11'd1;
                // cnt=0 时 rom_q 还是上一次的值, 从 cnt=1 起才有效
                if ((cnt >= 11'd1) && (cnt <= 11'd1024)) begin
                    O_wr_en   <= 1'b1;
                    O_wr_addr <= addr_d1;
                    O_wr_mag  <= mag_c;
                end else begin
                    O_wr_en   <= 1'b0;
                end
                if (cnt >= 11'd1025)
                    busy <= 1'b0;
            end
        end
    end

endmodule


// ============================================================================
// spec_demo_gen  --  多峰扫频演示源
//   噪声底 + 5 个窄带峰, 其中两个峰按三角波漂移, 用来演示动态效果。
// ============================================================================
module spec_demo_gen (
    input             I_clk        ,
    input             I_rst_n      ,
    input             I_frame_tick ,   // 每帧一个脉冲 (与 I_clk 同步)
    output reg        O_frame_start,
    output reg        O_wr_en      ,
    output reg [9:0]  O_wr_addr    ,
    output reg [15:0] O_wr_mag
);

    reg [10:0] cnt;        // 0..1023 写入计数
    reg        busy;
    reg [15:0] lfsr;       // 噪声源
    reg [7:0]  frame_cnt;  // 帧计数, 用于峰值漂移

    //------------------------------------------------------------------
    // 峰值位置漂移 (三角波)
    //------------------------------------------------------------------
    wire [6:0] tri_w = frame_cnt[7] ? ~frame_cnt[6:0] : frame_cnt[6:0];
    wire [9:0] c1    = 10'd240 + {3'd0, tri_w};            // 240..367
    wire [9:0] c2    = 10'd640;
    wire [9:0] c3    = 10'd96  + {4'd0, frame_cnt[7:1]};   // 96..223
    wire [9:0] c4    = 10'd880;
    wire [9:0] c5    = {c1[8:0], 1'b0};                    // 二次谐波

    wire [9:0] b = cnt[9:0];

    wire [9:0] d1 = (b >= c1) ? (b - c1) : (c1 - b);
    wire [9:0] d2 = (b >= c2) ? (b - c2) : (c2 - b);
    wire [9:0] d3 = (b >= c3) ? (b - c3) : (c3 - b);
    wire [9:0] d4 = (b >= c4) ? (b - c4) : (c4 - b);
    wire [9:0] d5 = (b >= c5) ? (b - c5) : (c5 - b);

    // 线性下降的峰形 (每远离 1 个频点下降 32 个幅度码)
    wire [11:0] a1 = (d1 < 10'd94) ? (12'd3400 - (d1 << 5)) : 12'd0;
    wire [11:0] a2 = (d2 < 10'd78) ? (12'd2500 - (d2 << 5)) : 12'd0;
    wire [11:0] a3 = (d3 < 10'd50) ? (12'd1600 - (d3 << 5)) : 12'd0;
    wire [11:0] a4 = (d4 < 10'd88) ? (12'd2800 - (d4 << 5)) : 12'd0;
    wire [11:0] a5 = (d5 < 10'd38) ? (12'd1200 - (d5 << 5)) : 12'd0;

    // 噪声底
    wire [11:0] noise = 12'd30 + {5'd0, lfsr[15:8]};

    wire [13:0] sum = {2'b00, noise} + {2'b00, a1} + {2'b00, a2} +
                      {2'b00, a3}    + {2'b00, a4} + {2'b00, a5};

    wire [11:0] mag_c = (sum > 14'd4095) ? 12'd4095 : sum[11:0];

    //------------------------------------------------------------------
    // 帧突发
    //------------------------------------------------------------------
    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            cnt           <= 11'd0;
            busy          <= 1'b0;
            lfsr          <= 16'hACE1;
            frame_cnt     <= 8'd0;
            O_frame_start <= 1'b0;
            O_wr_en       <= 1'b0;
            O_wr_addr     <= 10'd0;
            O_wr_mag      <= 16'd0;
        end else begin
            O_frame_start <= 1'b0;

            if (busy)
                lfsr <= {lfsr[14:0], lfsr[15] ^ lfsr[13] ^ lfsr[12] ^ lfsr[10]};

            if (!busy) begin
                O_wr_en <= 1'b0;
                if (I_frame_tick) begin
                    busy          <= 1'b1;
                    cnt           <= 11'd0;
                    frame_cnt     <= frame_cnt + 8'd1;
                    O_frame_start <= 1'b1;
                end
            end else begin
                O_wr_en   <= 1'b1;
                O_wr_addr <= cnt[9:0];
                O_wr_mag  <= {mag_c, 4'd0};   // 12bit -> 16bit 满量程
                cnt       <= cnt + 11'd1;
                if (cnt >= 11'd1023)
                    busy <= 1'b0;
            end
        end
    end

endmodule


