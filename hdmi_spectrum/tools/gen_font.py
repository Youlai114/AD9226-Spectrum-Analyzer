def glyph_row(ch, row):
    """返回 8bit 行数据, bit7 = 最左列"""
    pat = G.get(ch)
    if pat is None:
        raise KeyError("缺少字模: %r" % ch)
    s = pat[row]
    v = 0
    for i, c in enumerate(s):
        if c == '#':
            v |= (1 << (7 - i))
    return v


def gen_font():
    """生成同步 ROM (BSRAM), 索引 = {ch[6:0], row}, 共 1024 x 8bit"""
    lines = []
    lines.append("// ============================================================================")
    lines.append("// ui_font_rom.v  --  5x7 点阵字模 (由 tools/gen_font.py 自动生成, 请勿手改)")
    lines.append("// 同步读, 综合成 BSRAM ROM。索引 = {ch[6:0], row}, 8bit 行数据, bit7 = 最左列")
    lines.append("// ============================================================================")
    lines.append("")
    lines.append("module ui_font_rom (")
    lines.append("    input             I_clk  ,")
    lines.append("    input      [7:0]  I_ch   ,   // 字符 ASCII 码")
    lines.append("    input      [2:0]  I_row  ,   // 字模行 0..7")
    lines.append("    output reg [7:0]  O_bits     // 行点阵 (1 拍延迟)")
    lines.append(");")
    lines.append("")
    lines.append("    reg [7:0] rom [0:1023];")
    lines.append("")
    lines.append("    initial begin")
    for idx in range(1024):
        ch = idx >> 3
        row = idx & 7
        v = 0
        c = chr(ch)
        if c in G and row < 7:
            v = glyph_row(c, row)
        if v:
            lines.append("        rom[%4d] = 8'b%s;  // '%s' row%d"
                         % (idx, format(v, '08b'), c, row))
        else:
            lines.append("        rom[%4d] = 8'h00;" % idx)
    lines.append("    end")
    lines.append("")
    lines.append("    always @(posedge I_clk) O_bits <= rom[{I_ch[6:0], I_row}];")
    lines.append("")
    lines.append("endmodule")
    lines.append("")
    return "\n".join(lines)


def gen_text():
    """生成字符网格 ROM: 80 x 45 单元 (每单元 16x16 像素), 3 个量程层
       单元内容 = {scale, color[1:0], ch[7:0]}
       scale=0: 16x16 单元 (字高 16)   scale=1: 占 2x2 单元 (字高 32)"""

    W, H = 80, 45
    C_W, C_G, C_C, C_B = 0, 1, 2, 3     # 白 / 绿 / 青 / 蓝

    # 频率跨度档位 (顺序即按键循环顺序, 层 0 为上电默认)
    SPANS = [500e3, 1e6, 10e6]
    DBL = [["   0", " -10", " -20", " -30", " -40", " -50", " -60", " -70", " -80"]] * 3

    def fmt_hz(v):
        if v >= 1e6: return "%.6f MHz" % (v / 1e6)
        if v >= 1e3: return "%.3f kHz" % (v / 1e3)
        return "%.0f Hz" % v

    def fmt_short(v):            # 菜单按钮里的短格式
        if v >= 1e6: return "%g MHz" % (v / 1e6)
        if v >= 1e3: return "%g kHz" % (v / 1e3)
        return "%g Hz" % v

    def fmt_rbw(span):           # Hann 窗 ENBW = 1.5 x fs/2048, fs = 2 x Span
        rbw = 1.5 * (2 * span) / 2048
        if rbw >= 1e3: return "%.2f kHz" % (rbw / 1e3)
        return "%.0f Hz" % rbw

    def fmt_swt(span):           # 采集 2048 点的时间
        swt = 2048 / (2 * span)
        if swt >= 1e-3: return "%.3f ms" % (swt / 1e-3)
        return "%.1f us" % (swt / 1e-6)

    def layer(rng):
        g = [[(0, 0, 0)] * W for _ in range(H)]

        def put(c, r, txt, col=C_W):
            assert 0 <= c and c + len(txt) <= W and 0 <= r < H, (c, r, txt)
            for i, ch in enumerate(txt):
                g[r][c + i] = (ord(ch), col, 0)

        def put_big(c, r, txt, col=C_W):
            assert c + len(txt) * 2 <= W and r + 1 < H, (c, r, txt)
            for i, ch in enumerate(txt):
                for dy in (0, 1):
                    for dx in (0, 1):
                        g[r + dy][c + i * 2 + dx] = (ord(ch), col, 1)

        span = SPANS[rng]

        # ---------------- 顶栏 ----------------
        # 左上角标题 (两行 16px, 不用 32px 大字以免压到右边参数)
        put(1, 1, "SPECTRUM", C_C)
        put(1, 3, "ANALYZER", C_C)

        # 参数与实际链路对应:
        #   Center Freq = Span/2 = 500 kHz    Span = fs/2 = 1 MHz
        #   Ref = 0 dBFS (顶部满量程)         RBW = Hann 窗 ENBW = 1.5 x 976.56 Hz = 1.46 kHz
        #   SWT = 2048 点 / 2 MHz = 1.024 ms  Pts = 1024 (显示频点数)
        put(11, 1, "Center Freq:", C_W); put(24, 1, fmt_hz(span / 2),   C_G)
        put(11, 3, "Span:",        C_W); put(24, 3, fmt_hz(span),       C_G)
        put(37, 1, "Ref Level:",   C_W); put(48, 1, "0.00 dBFS",     C_G)
        put(38, 3, "RBW:",         C_W); put(48, 3, fmt_rbw(span),   C_G)

        # ---------------- 纵向刻度 (随量程) ----------------
        for k in range(9):
            put(0, 6 + 4 * k, DBL[rng][k], C_W)

        # 幅度单位 (绘图区左下角)
        put(5, 38, "dBFS", C_W)

        # ---------------- 频率刻度 (绘图区正下方, 随跨度) ----------------
        # 绘图区 8 大格, 边界在 cell 4,20,36,52,68; 标注每 2 格一个
        for k in range(5):
            v = span * k / 4.0
            txt = "0" if k == 0 else (("%gM" % (v / 1e6)) if v >= 1e6 else ("%gk" % (v / 1e3)))
            c = (4 + 16 * k) - len(txt) // 2
            if k == 4:
                c = 69 - len(txt)       # 最后一个右对齐到绘图区右边界
            put(c, 39, txt, C_W)

        # ---------------- 底栏 ----------------
        put(1,  40, "SWT: " + fmt_swt(span),   C_W)
        put(15, 40, "Start: 0 Hz",             C_W)
        put(27, 40, "Stop: " + fmt_hz(span),   C_W)
        put(47, 40, "Det: Pos Peak",           C_W)
        put(1,  42, "Win: Hann",               C_W)
        put(12, 42, "Pts: 1024",               C_W)
        put(23, 42, "Span: " + fmt_hz(span),   C_W)
        put(43, 42, "RBW: " + fmt_rbw(span),   C_W)

        # ---------------- 右侧菜单 ----------------
        put(74, 8,  "BW", C_B)
        put(71, 13, "Res BW",     C_B); put(69, 14, "1.0000 MHz", C_B)
        put(71, 18, "Avg Type",   C_B); put(74, 19, "Log",        C_B)
        put(71, 23, "Detector",   C_B); put(71, 24, "Pos Peak",   C_B)
        put(72, 28, "Trace",      C_B); put(69, 29, "Clear Write", C_B)
        put(74, 33, "Avg",        C_B); put(75, 34, "1",          C_B)
        put(72, 38, "Span",       C_B); put(69, 40, fmt_short(SPANS[rng]), C_B)
        put(74, 43, "1/2",        C_B)
        return g

    layers = [layer(i) for i in range(3)]

    lines = []
    lines.append("// ============================================================================")
    lines.append("// ui_text_rom.v  --  界面字符网格 (由 tools/gen_font.py 自动生成, 请勿手改)")
    lines.append("//")
    lines.append("//   屏幕按 16x16 像素划成 80 x 45 个单元, 每单元存一个字符:")
    lines.append("//     O_data = {scale, color[1:0], ch[7:0]}")
    lines.append("//     scale=0 : 字高 16 (占 1 个单元)")
    lines.append("//     scale=1 : 字高 32 (占 2x2 个单元, 四个单元内容相同)")
    lines.append("//   color: 0=白 1=绿 2=青 3=蓝")
    lines.append("//")
    lines.append("//   地址 = {I_range[1:0], cell[11:0]}, cell = (y>>4)*80 + (x>>4)")
    lines.append("//   每层按 4096 对齐 (地址 = range<<12 | cell), 共 3 x 4096 = 12288 项")
    lines.append("// ============================================================================")
    lines.append("")
    lines.append("module ui_text_rom (")
    lines.append("    input             I_clk  ,")
    lines.append("    input      [13:0] I_addr ,   // {range, cell}")
    lines.append("    output reg [10:0] O_data     // {scale, color, ch} (1 拍延迟)")
    lines.append(");")
    lines.append("")
    lines.append("    reg [10:0] rom [0:12287];")
    lines.append("")
    lines.append("    initial begin")
    for rng in range(3):
        for r in range(4096 // W):          # 每层补齐到 4096 项
            for c in range(W):
                if r < H:
                    ch, col, sc = layers[rng][r][c]
                else:
                    ch, col, sc = 0, 0, 0
                addr = rng * 4096 + r * W + c
                val = (sc << 10) | (col << 8) | ch
                if ch == 0:
                    lines.append("        rom[%5d] = 11'h000;" % addr)
                else:
                    lines.append("        rom[%5d] = 11'h%03X;  // r%d (%2d,%2d) '%s'"
                                 % (addr, val, rng, c, r, chr(ch)))
    lines.append("    end")
    lines.append("")
    lines.append("    always @(posedge I_clk) O_data <= rom[I_addr];")
    lines.append("")
    lines.append("endmodule")
    lines.append("")
    return "\n".join(lines)


